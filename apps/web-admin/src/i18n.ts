export const dictionaries: Record<Lang, Record<Key, string>> = { fr, en }

export function t(lang: Lang, key: Key, params: Record<string, string | number> = {}): string {
  const template = dictionaries[lang][key] ?? fr[key]
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? `{${name}}`))
}

export function browserLang(navigatorLanguage: string | undefined): Lang {
  return navigatorLanguage?.toLowerCase().startsWith('en') ? 'en' : 'fr'
}

/** Libellé d'une valeur d'énumération de l'API, ou la valeur brute si inconnue. */
export function label(lang: Lang, prefix: 'plan' | 'status' | 'tx' | 'severity' | 'service' | 'run' | 'cstatus' | 'usage' | 'qstatus' | 'mode' | 'cat' | 'tstatus' | 'prio' | 'tcat', value: string | null | undefined): string {
  if (!value) return t(lang, 'tx.none')
  const key = `${prefix}.${value}` as Key
  return key in fr ? t(lang, key) : value
}
